/**
 * Search local localities by query, boosting results that match the current city
 */
export function searchLocalities(query = '', currentCity = 'Moradabad', maxResults = 8) {
  const q = String(query || '').trim().toLowerCase();
  if (!q || q.length < 2) return [];

  const cityFilter = String(currentCity || '').trim().toLowerCase();

  const scored = [];

  for (const item of SERVICE_LOCALITIES) {
    let score = 0;
    const nameLower = item.name.toLowerCase();
    const areaLower = item.area.toLowerCase();
    const cityLower = item.city.toLowerCase();
    const pincode = item.pincode;

    if (nameLower.startsWith(q)) {
      score += 50;
    } else if (nameLower.includes(q)) {
      score += 30;
    }

    if (areaLower.includes(q)) {
      score += 20;
    }

    if (pincode.startsWith(q)) {
      score += 40;
    }

    for (const kw of item.keywords || []) {
      if (kw.includes(q)) {
        score += 15;
      }
    }

    // Boost score if matches current active city
    if (cityFilter && cityLower === cityFilter) {
      score += 25;
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, maxResults).map(s => s.item);
}

export default {
  SERVICE_LOCALITIES,
  searchLocalities
};
